// Deterministic realistic marks based on student name and index
function getRealisticScores(classId, index, name) {
  const hash = (name.charCodeAt(0) * 17 + index * 31 + name.length * 13) % 100;
  // Grade 7 & 8 subjects: khmer(100), math(100), physics(50), chem(50), bio(50), earth(50), history(50), geo(50), civics(50), eng(50), home(50), sport(50)
  // Grade 9 subjects: essay(60), dictation(40), math(100), physics(35), chem(25), bio(35), earth(25), history(33), geo(32), civics(35), eng(25)
  
  if (classId === '9A') {
    // 480 diploma system
    const base = 50 + (hash % 45); // 50 to 95 pct
    const factor = base / 100;
    return {
      essay: Math.round(60 * factor),
      dictation: Math.round(40 * factor),
      math: Math.round(100 * factor),
      physics: Math.round(35 * factor),
      chem: Math.round(25 * factor),
      bio: Math.round(35 * factor),
      earth: Math.round(25 * factor),
      history: Math.round(33 * factor),
      geo: Math.round(32 * factor),
      civics: Math.round(35 * factor),
      eng: Math.round(25 * factor)
    };
  }

  // 700 point system
  const base = 50 + (hash % 46);
  const factor = base / 100;
  return {
    khmer: Math.round(100 * factor),
    math: Math.round(100 * factor),
    physics: Math.round(50 * factor),
    chem: Math.round(50 * factor),
    bio: Math.round(50 * factor),
    earth: Math.round(50 * factor),
    history: Math.round(50 * factor),
    geo: Math.round(50 * factor),
    civics: Math.round(50 * factor),
    eng: Math.round(50 * factor),
    home: Math.round(50 * factor),
    sport: 45
  };
}

